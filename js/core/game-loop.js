// Send a chunk's data to the mesh worker. Called when the worker doesn't have
// the chunk yet, or when our version is newer than the worker's. Copies the
// chunk data into a fresh ArrayBuffer to avoid detaching the main thread's
// reference. Also sends the biome strip for the chunk.
// Takes STORAGE coords (cx, cz in [0, CHUNKS_X), [0, CHUNKS_Z))
function _syncChunkToMeshWorker(scx, scz) {
    if (!_meshWorker || !_meshWorkerReady) return false;
    if (scx < 0 || scx >= CHUNKS_X || scz < 0 || scz >= CHUNKS_Z) return false;
    const chunk = chunkStorageArr[scx * CHUNKS_Z + scz];
    if (!chunk) return false;
    
    const key = scx + ',' + scz;
    const myVersion = _mainThreadChunkVersions.get(key) || 0;
    const workerVersion = _meshWorkerChunkVersions.get(key);
    if (workerVersion !== undefined && workerVersion >= myVersion) return true; // already up to date
    
    // Copy the chunk data so we don't detach our own reference
    const copy = new Int32Array(chunk.length);
    copy.set(chunk);
    
    _meshWorker.postMessage({
        type: 'setChunk',
        cx: scx,
        cz: scz,
        chunkBuf: copy.buffer
    }, [copy.buffer]);
    
    // Send biome strip when its biome data is actually present in the main
    // thread biomeMap. If we send it too early (before biomes are populated),
    // the worker locks in 'plains' tints permanently. So only mark "sent" if
    // every cell had real data — otherwise allow retry on the next mesh request.
    if (!_biomeStripsSent.has(key)) {
        const biomeStrip = new Uint8Array(CHUNK_SIZE * CHUNK_SIZE);
        const startX = scx * CHUNK_SIZE; // storage X start (no halfW offset)
        const startZ = scz * CHUNK_SIZE;
        let realCount = 0;
        // Dimension-aware default biome ID for cells with no real data.
        // Without this, undefined cells default to plains (id=4), which gives
        // overworld plains tints to aether/nether terrain. The mesh worker
        // only sees ID numbers and doesn't know what dimension it's rendering,
        // so we encode the dimension into the default at the main thread level.
        // For aether, default to skyforest (not void) so cells without explicit
        // biome data — especially chunks loaded from save where aetherBiomeMap
        // wasn't persisted — render with the correct skyforest tint instead of
        // an aether_void tint that would still look wrong.
        let defaultId = 4; // plains
        if (typeof currentDimension !== 'undefined' && currentDimension === 'aether') {
            defaultId = 10; // aether_skyforest
        }
        for (let lx = 0; lx < CHUNK_SIZE; lx++) {
            for (let lz = 0; lz < CHUNK_SIZE; lz++) {
                const ix = startX + lx;
                const iz = startZ + lz;
                const gIdx = ix + iz * WORLD_WIDTH;
                const biomeName = (gIdx >= 0 && gIdx < WORLD_WIDTH * WORLD_DEPTH) ? biomeMap[gIdx] : null;
                if (biomeName) realCount++;
                // Map name -> ID (must match BIOME_NAMES_LIST in worker).
                let id = defaultId;
                switch (biomeName) {
                    case 'desert': id = 0; break;
                    case 'rainforest': id = 1; break;
                    case 'tundra': id = 2; break;
                    case 'taiga': id = 3; break;
                    case 'plains': id = 4; break;
                    case 'forest': id = 5; break;
                    case 'ocean': id = 6; break;
                    case 'swamp': id = 7; break;
                    case 'jungle': id = 8; break;
                    case 'extreme_hills': id = 9; break;
                    case 'aether_skyforest': id = 10; break;
                    case 'aether_void': id = 11; break;
                    case 'aether_lake': id = 12; break;
                }
                biomeStrip[lx + lz * CHUNK_SIZE] = id;
            }
        }
        _meshWorker.postMessage({
            type: 'setBiomeStrip',
            cx: scx,
            cz: scz,
            biomesBuf: biomeStrip.buffer
        }, [biomeStrip.buffer]);
        // Only mark as "sent" (i.e. don't resend) if every cell was real data.
        // Otherwise allow a retry on the next mesh request when more biomes
        // may have been generated.
        if (realCount === CHUNK_SIZE * CHUNK_SIZE) {
            _biomeStripsSent.add(key);
        }
    }
    
    _meshWorkerChunkVersions.set(key, myVersion);
    return true;
}

// Request the mesh worker to build a mesh for a chunk.
// Takes WORLD chunk coords (matching buildChunkMesh API).
// First syncs the chunk + 8 neighbors if needed, then posts the mesh request.
// Returns true if dispatched, false if not (e.g. worker not ready or already pending).
function requestMeshFromWorker(wcx, wcz) {
    if (!_meshWorker || !_meshWorkerReady) return false;
    // Mesh worker is now dimension-agnostic (Phase 3). It builds meshes for
    // overworld, nether, and aether chunks alike. The worker's chunk mirror
    // is reset on dimension change via notifyDimensionChange so it never
    // mixes chunks from different dimensions.
    // Convert world coords to storage indices
    const scx = wcx + (CHUNKS_X >> 1);
    const scz = wcz + (CHUNKS_Z >> 1);
    if (scx < 0 || scx >= CHUNKS_X || scz < 0 || scz >= CHUNKS_Z) return false;
    const chunk = chunkStorageArr[scx * CHUNKS_Z + scz];
    if (!chunk) return false;
    
    const key = wcx + ',' + wcz;
    if (_pendingMeshRequests.has(key)) return true; // already in flight
    
    // Sync this chunk + 8 neighbors to the worker (using storage coords)
    for (let dx = -1; dx <= 1; dx++) {
        for (let dz = -1; dz <= 1; dz++) {
            _syncChunkToMeshWorker(scx + dx, scz + dz);
        }
    }
    
    _pendingMeshRequests.add(key);
    // Send the mesh request using world coords (worker's _buildChunkMeshDataOnly expects world coords)
    _meshWorker.postMessage({ type: 'mesh', wcx: wcx, wcz: wcz });
    return true;
}
window.requestMeshFromWorker = requestMeshFromWorker;

// Receive mesh data from the worker, copy it into the _cm_* arrays, and call
// _assembleChunkMeshFromArrays to create the THREE objects on the main thread.
// Worker sends wcx/wcz (world chunk coords).
function _onMeshWorkerDone(msg) {
    const cx = msg.wcx, cz = msg.wcz;
    const key = cx + ',' + cz;
    _pendingMeshRequests.delete(key);
    _meshWorkerCompletedThisFrame++;
    
    if (msg.empty) {
        // Worker had no data — fall back to inline build
        try { buildChunkMesh(cx, cz); } catch (e) { console.error('inline mesh fallback failed:', e); }
        return;
    }
    
    try {
        // Pass the worker's typed arrays directly to BufferAttribute. No copy
        // loops — the previous version was the #1 hottest function in the game
        // (18% of total CPU) because it did .push() per element across 36 arrays.
        if (typeof _assembleChunkMeshFromTypedArrays === 'function') {
            _assembleChunkMeshFromTypedArrays(cx, cz, msg);
        } else {
            // Defensive fallback if the new assembly function isn't loaded yet
            buildChunkMesh(cx, cz);
        }
    } catch (e) {
        console.error('[mesh-worker] handoff failed for chunk', cx, cz, ':', e);
        try { buildChunkMesh(cx, cz); } catch (e2) { console.error(e2); }
    }
}

