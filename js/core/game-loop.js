// Notify the worker that worldgen settings have changed (e.g., from menu)
function notifyWorldgenWorkerSettingsChanged(reinitNoise) {
    if (!_worldgenWorker) return;
    _worldgenWorker.postMessage({
        type: 'updateSettings',
        settings: _gatherWorldgenSettings(),
        reinitNoise: !!reinitNoise
    });
}
window.notifyWorldgenWorkerSettingsChanged = notifyWorldgenWorkerSettingsChanged;

// Request the worker to generate a chunk. Returns true if dispatched, false if not
// (e.g., worker not ready, chunk already pending, chunk already generated).
// In the not-ready case, caller can fall back to inline gen.
function requestWorkerChunkGen(cx, cz) {
    if (!_worldgenWorker || !_workerReady) return false;
    if (cx < 0 || cx >= CHUNKS_X || cz < 0 || cz >= CHUNKS_Z) return false;
    if (_isChunkGenerated(cx, cz)) return false;
    const key = cx + ',' + cz;
    if (_pendingWorkerChunks.has(key)) return false;
    _pendingWorkerChunks.add(key);
    _worldgenWorker.postMessage({ type: 'gen', cx: cx, cz: cz });
    return true;
}

// Called when the worker delivers a finished chunk. Copy the chunk data into
// chunkStorageArr, restore biomes to biomeMap, replay collected events, and
// queue the chunk + neighbors for meshing and lighting.
function _onWorkerChunkDone(msg) {
    const cx = msg.cx, cz = msg.cz;
    const key = cx + ',' + cz;
    _pendingWorkerChunks.delete(key);
    
    if (cx < 0 || cx >= CHUNKS_X || cz < 0 || cz >= CHUNKS_Z) return;
    
    // Drop response if we're no longer in the overworld. This prevents
    // overworld chunks that were in flight at dimension-switch time from
    // being adopted into the new dimension's chunk storage (which would
    // appear as a strip of overworld terrain in the nether/aether).
    if (typeof currentDimension !== 'undefined' && currentDimension !== 'overworld') return;
    
    // Skip if main thread already generated this chunk somehow (race condition guard)
    if (_isChunkGenerated(cx, cz)) return;
    
    // Adopt the transferred buffer as our chunk
    const chunkData = new Int32Array(msg.chunkBuf);
    const idx = cx * CHUNKS_Z + cz;
    chunkStorageArr[idx] = chunkData;
    _markChunkGenerated(cx, cz);
    // Bump version so the mesh worker re-syncs this chunk on its next request.
    // Without this, the version cache thinks the worker already has this chunk
    // (because both versions are 0), and meshes neighboring chunks with stale
    // or missing data — causing the water-faces-in-the-middle bug, leaves
    // cut off at borders, and incomplete biome smoothing at edges.
    bumpChunkVersion(cx, cz);
    
    // Apply any deferred overflow writes that were queued for THIS chunk
    // by previously-generated neighbor chunks (e.g. tree leaves spilling in)
    const myKey = cx + ',' + cz;
    if (_deferredOverflowWrites.has(myKey)) {
        const flat = _deferredOverflowWrites.get(myKey);
        for (let i = 0; i < flat.length; i += 7) {
            const wx = flat[i], wy = flat[i+1], wz = flat[i+2];
            const id = flat[i+3], level = flat[i+4], falling = flat[i+5], source = flat[i+6];
            // Only write to air — don't overwrite existing terrain (especially tree trunks)
            if ((getVoxel(wx, wy, wz) & 0xFF) === 0) {
                setVoxel(wx, wy, wz, id, level, falling, source);
            }
        }
        _deferredOverflowWrites.delete(myKey);
    }
    
    // Apply overflow writes from THIS chunk into neighbor chunks (or defer if neighbor missing)
    if (msg.overflow && msg.overflow.length > 0) {
        const halfWO = WORLD_WIDTH / 2;
        const halfDO = WORLD_DEPTH / 2;
        for (let i = 0; i < msg.overflow.length; i += 7) {
            const wx = msg.overflow[i], wy = msg.overflow[i+1], wz = msg.overflow[i+2];
            const id = msg.overflow[i+3], level = msg.overflow[i+4];
            const falling = msg.overflow[i+5], source = msg.overflow[i+6];
            // Compute target chunk coords
            const tcx = ((wx + halfWO) | 0) >> 4;
            const tcz = ((wz + halfDO) | 0) >> 4;
            if (tcx < 0 || tcx >= CHUNKS_X || tcz < 0 || tcz >= CHUNKS_Z) continue;
            if (_isChunkGenerated(tcx, tcz)) {
                // Target chunk exists — write directly (only into air to preserve trunks/etc)
                if ((getVoxel(wx, wy, wz) & 0xFF) === 0) {
                    setVoxel(wx, wy, wz, id, level, falling, source);
                }
                // Mark target chunk dirty for re-meshing (deferred for after lighting)
                const tWcx = tcx - CHUNKS_X / 2;
                const tWcz = tcz - CHUNKS_Z / 2;
                if (!window._pendingMeshFromWorker) window._pendingMeshFromWorker = [];
                window._pendingMeshFromWorker.push(tWcx + ',' + tWcz);
            } else {
                // Target chunk not yet generated — queue for later
                const tKey = tcx + ',' + tcz;
                let arr = _deferredOverflowWrites.get(tKey);
                if (!arr) { arr = []; _deferredOverflowWrites.set(tKey, arr); }
                arr.push(wx, wy, wz, id, level, falling, source);
            }
        }
    }
    
    // Restore biome data into the global biomeMap
    const biomes = new Uint8Array(msg.biomesBuf);
    const halfW = WORLD_WIDTH / 2;
    const halfD = WORLD_DEPTH / 2;
    const startX = cx * CHUNK_SIZE - halfW;
    const startZ = cz * CHUNK_SIZE - halfD;
    for (let lx = 0; lx < CHUNK_SIZE; lx++) {
        for (let lz = 0; lz < CHUNK_SIZE; lz++) {
            const wx = startX + lx;
            const wz = startZ + lz;
            const gIdx = (wx + halfW) + (wz + halfD) * WORLD_WIDTH;
            if (gIdx >= 0 && gIdx < WORLD_WIDTH * WORLD_DEPTH) {
                biomeMap[gIdx] = BIOME_NAMES[biomes[lx + lz * CHUNK_SIZE]];
            }
        }
    }
    
    // Replay mob spawns (with the real cap check this time)
    if (msg.mobs && msg.mobs.length > 0) {
        const mobCap = (typeof MOB_CAP_PASSIVE !== 'undefined') ? MOB_CAP_PASSIVE : 10;
        for (const m of msg.mobs) {
            if (typeof globalMobs !== 'undefined' && typeof _isPassiveMob === 'function') {
                const passiveCount = globalMobs.filter(_isPassiveMob).length;
                if (passiveCount >= mobCap) break;
            }
            if (typeof spawnMob === 'function') {
                spawnMob(m.type, m.x, m.y, m.z);
            }
        }
    }
    // Replay spawner registrations
    if (msg.spawners && msg.spawners.length > 0 && typeof window.registerSpawner === 'function') {
        for (const s of msg.spawners) window.registerSpawner(s.x, s.y, s.z);
    }
    // Replay loot chest fills
    if (msg.chests && msg.chests.length > 0 && typeof window.fillLootChest === 'function') {
        for (const c of msg.chests) window.fillLootChest(c.x, c.y, c.z);
    }
    
    // Queue chunk + neighbors for meshing — but DEFER adding to dirtyChunks
    // until lighting has been computed for them. Otherwise the chunks render
    // dark for several frames until the next lighting recalc catches them up.
    const wcx = cx - CHUNKS_X / 2;
    const wcz = cz - CHUNKS_Z / 2;
    
    // Queue lighting recalc center for this chunk, with the dirty-mark
    // chunk keys to apply AFTER lighting completes for this chunk.
    // Mark all 8 surrounding neighbors (not just 4 cardinal) so leaves that
    // overhang into corner neighbors, water faces at chunk corners, and biome
    // smoothing at corners all get re-meshed with the fresh data.
    _pendingLightingChunks.push({
        cx_center: wcx * CHUNK_SIZE + CHUNK_SIZE / 2,
        cz_center: wcz * CHUNK_SIZE + CHUNK_SIZE / 2,
        meshKeys: [
            wcx + ',' + wcz,
            (wcx + 1) + ',' + wcz,
            (wcx - 1) + ',' + wcz,
            wcx + ',' + (wcz + 1),
            wcx + ',' + (wcz - 1),
            (wcx + 1) + ',' + (wcz + 1),
            (wcx + 1) + ',' + (wcz - 1),
            (wcx - 1) + ',' + (wcz + 1),
            (wcx - 1) + ',' + (wcz - 1)
        ]
    });
    
    _workerCompletedThisFrame++;
}
window.spawnWorldgenWorker = spawnWorldgenWorker;
window.requestWorkerChunkGen = requestWorkerChunkGen;

