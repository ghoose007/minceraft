// ==========================================
// WORLDGEN WORKER (background chunk generation)
// ==========================================
// The worldgen worker generates chunks in a background thread so the main
// thread stays responsive during chunk streaming. Without this, each lazy
// chunk gen blocks the main thread for ~5-10ms, causing FPS dips.
// 
// If the worker fails to start (e.g., file:// protocol with no CORS, or
// the browser blocks workers), we fall back to inline synchronous generation.

let _worldgenWorker = null;
let _workerReady = false;
let _workerInitInFlight = false;
const _pendingWorkerChunks = new Set(); // Set of "cx,cz" keys currently being generated by worker
const _pendingLightingChunks = []; // Array of {cx_center, cz_center} added when worker chunks come back
let _workerCompletedThisFrame = 0; // Diagnostic: chunks completed by worker this frame

// Cross-chunk writes from worker chunks (e.g. tree leaves spilling into neighbor).
// Keyed by "cx,cz" of the TARGET chunk. Each value is a flat array of 7-tuples
// [wx, wy, wz, id, level, falling, source, ...]. When that chunk gets generated
// in the future, we apply these writes on top.
const _deferredOverflowWrites = new Map();

// Spawn the worker and send initial settings. Called once per world load.
function spawnWorldgenWorker() {
    console.log('[worldgen-worker] spawning...');
    if (_worldgenWorker) {
        try { _worldgenWorker.terminate(); } catch(e) {}
        _worldgenWorker = null;
    }
    _workerReady = false;
    _workerInitInFlight = false;
    _pendingWorkerChunks.clear();
    _pendingLightingChunks.length = 0;
    
    if (typeof Worker === 'undefined') {
        console.warn('Web Workers not supported, falling back to inline worldgen');
        return;
    }
    
    try {
        _worldgenWorker = new Worker('js/workers/worldgen-worker.js?v=' + (typeof ASSET_VERSION !== 'undefined' ? ASSET_VERSION : Date.now()));
    } catch (e) {
        console.warn('Failed to spawn worldgen worker, falling back to inline gen:', e);
        _worldgenWorker = null;
        return;
    }
    
    _worldgenWorker.onerror = function(ev) {
        console.error('[worldgen-worker] error:', ev.message, ev.filename, ev.lineno);
        _workerReady = false;
    };
    
    _worldgenWorker.onmessage = function(ev) {
        const msg = ev.data;
        if (msg.type === 'initDone') {
            _workerReady = true;
            _workerInitInFlight = false;
            console.log('[worldgen-worker] ready');
            return;
        }
        if (msg.type === 'error') {
            console.error('[worldgen-worker] init error:', msg.error);
            _workerReady = false;
            _workerInitInFlight = false;
            return;
        }
        if (msg.type === 'genError') {
            console.error('[worldgen-worker] gen error for chunk', msg.cx, msg.cz, ':', msg.error);
            _pendingWorkerChunks.delete(msg.cx + ',' + msg.cz);
            return;
        }
        if (msg.type === 'genDone') {
            _onWorkerChunkDone(msg);
            return;
        }
    };
    
    // Send init message with all the constants and settings the worker needs
    _workerInitInFlight = true;
    _worldgenWorker.postMessage({
        type: 'init',
        WORLD_WIDTH: WORLD_WIDTH,
        WORLD_DEPTH: WORLD_DEPTH,
        CHUNKS_X: CHUNKS_X,
        CHUNKS_Z: CHUNKS_Z,
        CHUNK_VOLUME: CHUNK_VOLUME,
        worldSeed: _worldSeed,
        settings: _gatherWorldgenSettings()
    });
}

