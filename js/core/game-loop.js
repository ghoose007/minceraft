// Spawn the nether worker. Lazy — called from requestNetherChunkGen the first
// time it's needed, or from notifyDimensionChange when entering nether.
function spawnNetherWorker() {
    console.log('[nether-worker] spawning...');
    if (_netherWorker) {
        try { _netherWorker.terminate(); } catch(e) {}
        _netherWorker = null;
    }
    _netherWorkerReady = false;
    _netherWorkerInitInFlight = false;
    _pendingNetherChunks.clear();
    
    if (typeof Worker === 'undefined') {
        console.warn('Web Workers not supported, nether will use inline gen');
        return;
    }
    
    try {
        _netherWorker = new Worker('js/workers/nether-worker.js?v=' + (typeof ASSET_VERSION !== 'undefined' ? ASSET_VERSION : Date.now()));
    } catch (e) {
        console.warn('Failed to spawn nether worker, falling back to inline gen:', e);
        _netherWorker = null;
        return;
    }
    
    _netherWorker.onerror = function(ev) {
        console.error('[nether-worker] error:', ev.message, ev.filename, ev.lineno);
        _netherWorkerReady = false;
    };
    
    _netherWorker.onmessage = function(ev) {
        const msg = ev.data;
        if (msg.type === 'initDone') {
            _netherWorkerReady = true;
            _netherWorkerInitInFlight = false;
            console.log('[nether-worker] ready');
            return;
        }
        if (msg.type === 'error') {
            console.error('[nether-worker] init error:', msg.error);
            _netherWorkerReady = false;
            _netherWorkerInitInFlight = false;
            return;
        }
        if (msg.type === 'genError') {
            console.error('[nether-worker] gen error for chunk', msg.cx, msg.cz, ':', msg.error);
            _pendingNetherChunks.delete(msg.cx + ',' + msg.cz);
            return;
        }
        if (msg.type === 'genDone') {
            _onNetherWorkerChunkDone(msg);
            return;
        }
    };
    
    // Send init message
    _netherWorkerInitInFlight = true;
    _netherWorker.postMessage({
        type: 'init',
        WORLD_WIDTH: WORLD_WIDTH,
        WORLD_DEPTH: WORLD_DEPTH,
        CHUNKS_X: CHUNKS_X,
        CHUNKS_Z: CHUNKS_Z,
        CHUNK_VOLUME: CHUNK_VOLUME,
        worldSeed: _worldSeed,
        settings: _gatherNetherSettings()
    });
}
window.spawnNetherWorker = spawnNetherWorker;

// Request the nether worker to generate a chunk. Lazy-spawns the worker
// the first time this is called. Returns true if dispatched.
function requestNetherChunkGen(cx, cz) {
    // Lazy spawn on first request
    if (!_netherWorker && !_netherWorkerInitInFlight) {
        spawnNetherWorker();
    }
    if (!_netherWorker || !_netherWorkerReady) return false;
    if (typeof currentDimension !== 'undefined' && currentDimension !== 'nether') return false;
    if (cx < 0 || cx >= CHUNKS_X || cz < 0 || cz >= CHUNKS_Z) return false;
    if (_isChunkGenerated(cx, cz)) return false;
    const key = cx + ',' + cz;
    if (_pendingNetherChunks.has(key)) return false;
    _pendingNetherChunks.add(key);
    _netherWorker.postMessage({ type: 'gen', cx: cx, cz: cz });
    return true;
}
window.requestNetherChunkGen = requestNetherChunkGen;

// Receive a generated nether chunk from the worker. Adopts it into
// chunkStorageArr, applies any overflow writes, queues lighting + dirty
// re-mesh. Mirrors _onWorkerChunkDone but simpler — no biomes, no mob/
// spawner/chest replay.
function _onNetherWorkerChunkDone(msg) {
    const cx = msg.cx, cz = msg.cz;
    const key = cx + ',' + cz;
    _pendingNetherChunks.delete(key);
    
    // Drop response if we're no longer in the nether (player portaled out
    // while the chunk was being generated).
    if (typeof currentDimension !== 'undefined' && currentDimension !== 'nether') return;
    
    if (cx < 0 || cx >= CHUNKS_X || cz < 0 || cz >= CHUNKS_Z) return;
    if (_isChunkGenerated(cx, cz)) return;
    
    // Adopt the transferred buffer as our chunk
    const chunkData = new Int32Array(msg.chunkBuf);
    const idx = cx * CHUNKS_Z + cz;
    chunkStorageArr[idx] = chunkData;
    _markChunkGenerated(cx, cz);
    // Bump version so the mesh path knows this chunk is fresh
    bumpChunkVersion(cx, cz);
    
    // Apply any deferred overflow writes from earlier neighbor gens
    const myKey = cx + ',' + cz;
    if (_deferredOverflowWrites.has(myKey)) {
        const flat = _deferredOverflowWrites.get(myKey);
        for (let i = 0; i < flat.length; i += 7) {
            const wx = flat[i], wy = flat[i+1], wz = flat[i+2];
            const id = flat[i+3], level = flat[i+4], falling = flat[i+5], source = flat[i+6];
            if ((getVoxel(wx, wy, wz) & 0xFF) === 0) {
                setVoxel(wx, wy, wz, id, level, falling, source);
            }
        }
        _deferredOverflowWrites.delete(myKey);
    }
    
    // Apply this chunk's overflow writes into neighbors (or defer)
    if (msg.overflow && msg.overflow.length > 0) {
        const halfWO = WORLD_WIDTH / 2;
        const halfDO = WORLD_DEPTH / 2;
        for (let i = 0; i < msg.overflow.length; i += 7) {
            const wx = msg.overflow[i], wy = msg.overflow[i+1], wz = msg.overflow[i+2];
            const id = msg.overflow[i+3], level = msg.overflow[i+4];
            const falling = msg.overflow[i+5], source = msg.overflow[i+6];
            const tcx = ((wx + halfWO) | 0) >> 4;
            const tcz = ((wz + halfDO) | 0) >> 4;
            if (tcx < 0 || tcx >= CHUNKS_X || tcz < 0 || tcz >= CHUNKS_Z) continue;
            if (_isChunkGenerated(tcx, tcz)) {
                if ((getVoxel(wx, wy, wz) & 0xFF) === 0) {
                    setVoxel(wx, wy, wz, id, level, falling, source);
                }
            } else {
                const tKey = tcx + ',' + tcz;
                let arr = _deferredOverflowWrites.get(tKey);
                if (!arr) { arr = []; _deferredOverflowWrites.set(tKey, arr); }
                arr.push(wx, wy, wz, id, level, falling, source);
            }
        }
    }
    
    // Queue lighting + dirty re-mesh for this chunk and its 8 neighbors,
    // matching the overworld pipeline.
    const wcx = cx - CHUNKS_X / 2;
    const wcz = cz - CHUNKS_Z / 2;
    _pendingLightingChunks.push({
        cx_center: wcx * CHUNK_SIZE + CHUNK_SIZE / 2,
        cz_center: wcz * CHUNK_SIZE + CHUNK_SIZE / 2,
        meshKeys: [
            wcx + ',' + wcz,
            (wcx + 1) + ',' + wcz,
            (wcx - 1) + ',' + wcz,
            wcx + ',' + (wcz + 1),
            wcx + ',' + (wcz - 1),
            (wcx + 1) + ',' + (wcz + 1),
            (wcx + 1) + ',' + (wcz - 1),
            (wcx - 1) + ',' + (wcz + 1),
            (wcx - 1) + ',' + (wcz - 1)
        ]
    });
    
    _workerCompletedThisFrame++;
}

