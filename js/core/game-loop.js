// Map worker biome IDs back to names. Must match aether-worker.js
// _aetherBiomeNameToId.
const _AETHER_BIOME_ID_TO_NAME = ['aether_void', 'aether_skyforest', 'aether_lake'];

function _onAetherWorkerChunkDone(msg) {
    const cx = msg.cx, cz = msg.cz;
    const key = cx + ',' + cz;
    _pendingAetherChunks.delete(key);
    
    // Drop response if we're no longer in the aether
    if (typeof currentDimension !== 'undefined' && currentDimension !== 'aether') return;
    
    if (cx < 0 || cx >= CHUNKS_X || cz < 0 || cz >= CHUNKS_Z) return;
    if (_isChunkGenerated(cx, cz)) return;
    
    // Adopt the chunk
    const chunkData = new Int32Array(msg.chunkBuf);
    const idx = cx * CHUNKS_Z + cz;
    chunkStorageArr[idx] = chunkData;
    _markChunkGenerated(cx, cz);
    bumpChunkVersion(cx, cz);
    
    // Restore biome data into the main thread biomeMap
    if (msg.biomesBuf) {
        const biomes = new Uint8Array(msg.biomesBuf);
        const startX = cx * CHUNK_SIZE - WORLD_WIDTH / 2;
        const startZ = cz * CHUNK_SIZE - WORLD_DEPTH / 2;
        const halfW = WORLD_WIDTH / 2;
        const halfD = WORLD_DEPTH / 2;
        for (let lx = 0; lx < CHUNK_SIZE; lx++) {
            for (let lz = 0; lz < CHUNK_SIZE; lz++) {
                const wx = startX + lx;
                const wz = startZ + lz;
                const gIdx = (wx + halfW) + (wz + halfD) * WORLD_WIDTH;
                if (gIdx >= 0 && gIdx < WORLD_WIDTH * WORLD_DEPTH) {
                    const id = biomes[lx + lz * CHUNK_SIZE];
                    biomeMap[gIdx] = _AETHER_BIOME_ID_TO_NAME[id] || 'aether_void';
                }
            }
        }
    }
    
    // Apply deferred overflow writes that were queued for THIS chunk
    const myKey = cx + ',' + cz;
    if (_deferredOverflowWrites.has(myKey)) {
        const flat = _deferredOverflowWrites.get(myKey);
        for (let i = 0; i < flat.length; i += 7) {
            const wx = flat[i], wy = flat[i+1], wz = flat[i+2];
            const id = flat[i+3], level = flat[i+4], falling = flat[i+5], source = flat[i+6];
            if ((getVoxel(wx, wy, wz) & 0xFF) === 0) {
                setVoxel(wx, wy, wz, id, level, falling, source);
            }
        }
        _deferredOverflowWrites.delete(myKey);
    }
    
    // Apply this chunk's overflow into neighbors (or defer)
    if (msg.overflow && msg.overflow.length > 0) {
        const halfWO = WORLD_WIDTH / 2;
        const halfDO = WORLD_DEPTH / 2;
        for (let i = 0; i < msg.overflow.length; i += 7) {
            const wx = msg.overflow[i], wy = msg.overflow[i+1], wz = msg.overflow[i+2];
            const id = msg.overflow[i+3], level = msg.overflow[i+4];
            const falling = msg.overflow[i+5], source = msg.overflow[i+6];
            const tcx = ((wx + halfWO) | 0) >> 4;
            const tcz = ((wz + halfDO) | 0) >> 4;
            if (tcx < 0 || tcx >= CHUNKS_X || tcz < 0 || tcz >= CHUNKS_Z) continue;
            if (_isChunkGenerated(tcx, tcz)) {
                if ((getVoxel(wx, wy, wz) & 0xFF) === 0) {
                    setVoxel(wx, wy, wz, id, level, falling, source);
                }
            } else {
                const tKey = tcx + ',' + tcz;
                let arr = _deferredOverflowWrites.get(tKey);
                if (!arr) { arr = []; _deferredOverflowWrites.set(tKey, arr); }
                arr.push(wx, wy, wz, id, level, falling, source);
            }
        }
    }
    
    // Queue lighting + dirty re-mesh for this chunk and 8 neighbors.
    // Aether terrain is at higher Y values than overworld/nether (islands
    // float at Y=60-120+), so we need a higher Y center for the lighting BFS
    // to reach the top of the islands. The lighting covers [0, uy+14], so
    // uy=110 covers up to Y=124 — enough to cover all aether terrain.
    const wcx = cx - CHUNKS_X / 2;
    const wcz = cz - CHUNKS_Z / 2;
    _pendingLightingChunks.push({
        cx_center: wcx * CHUNK_SIZE + CHUNK_SIZE / 2,
        cy_center: 110,
        cz_center: wcz * CHUNK_SIZE + CHUNK_SIZE / 2,
        meshKeys: [
            wcx + ',' + wcz,
            (wcx + 1) + ',' + wcz,
            (wcx - 1) + ',' + wcz,
            wcx + ',' + (wcz + 1),
            wcx + ',' + (wcz - 1),
            (wcx + 1) + ',' + (wcz + 1),
            (wcx + 1) + ',' + (wcz - 1),
            (wcx - 1) + ',' + (wcz + 1),
            (wcx - 1) + ',' + (wcz - 1)
        ]
    });
    
    _workerCompletedThisFrame++;
}

// Called by dimension-switch.js whenever the player changes dimensions.
// Clears worker tracking state so stale in-flight chunks from the previous
// dimension don't get adopted into the new dimension's chunk storage.
// Also lazy-spawns the nether/aether workers on first entry to those dims.
function notifyDimensionChange() {
    _pendingWorkerChunks.clear();
    _pendingNetherChunks.clear();
    _pendingAetherChunks.clear();
    _pendingMeshRequests.clear();
    // Clear deferred overflow writes — they were keyed for the previous
    // dimension's chunk layout and don't apply to the new one.
    _deferredOverflowWrites.clear();
    // Clear pending lighting queue so we don't apply old-dimension lighting
    // to new-dimension chunks.
    _pendingLightingChunks.length = 0;
    
    // Reset the mesh worker on dimension change. The worker holds a mirror
    // of chunkStorageArr and biomeMap; if we don't reset, it would still
    // contain the previous dimension's chunk data and serve stale meshes.
    // We also clear the main-thread version cache and biome strip tracking
    // so the next mesh requests re-sync everything. Without this, the main
    // thread thinks the worker already has chunks at version N, and the
    // worker would skip syncing → empty meshes everywhere.
    //
    // CRITICAL: pass the new dimension's WORLD_WIDTH/CHUNKS_X so the worker
    // reallocates its arrays to the right size. Different dimensions can
    // have different world sizes (the nether is smaller than the overworld),
    // and without reallocation the worker's flat arrays would be the wrong
    // shape — setBiomeStrip writes and the smoothing kernel reads would
    // land on different cells, causing constant mesh churn and broken tints.
    if (_meshWorker && _meshWorkerReady) {
        try {
            _meshWorker.postMessage({
                type: 'reset',
                WORLD_WIDTH: WORLD_WIDTH,
                WORLD_DEPTH: WORLD_DEPTH,
                CHUNKS_X: CHUNKS_X,
                CHUNKS_Z: CHUNKS_Z,
                CHUNK_VOLUME: CHUNK_VOLUME
            });
        } catch (e) {}
    }
    _meshWorkerChunkVersions.clear();
    _mainThreadChunkVersions.clear();
    _biomeStripsSent.clear();
    
    // For aether: pre-fill the main thread biomeMap with 'aether_skyforest'
    // for any cell that's currently undefined. This handles three cases:
    //   1. Newly-created aether dimension (biomeMap is fresh empty array)
    //   2. Aether loaded from save (chunks restored but aetherBiomeMap not persisted)
    //   3. Areas the player hasn't generated yet
    // The smoothing kernel reads ±2 cells around each block, so cells near
    // the edge of an island would otherwise pick up undefined neighbors and
    // default to plains, producing muddy tints. Pre-filling with skyforest
    // ensures the smoothing kernel always sees aether-themed colors.
    // Note: aether's gen will OVERWRITE specific cells with 'aether_void' or
    // 'aether_lake' as appropriate, so this is a baseline default, not a
    // forced override.
    if (typeof currentDimension !== 'undefined' && currentDimension === 'aether'
        && typeof biomeMap !== 'undefined' && biomeMap) {
        const len = biomeMap.length || (WORLD_WIDTH * WORLD_DEPTH);
        for (let i = 0; i < len; i++) {
            if (biomeMap[i] === undefined || biomeMap[i] === null) {
                biomeMap[i] = 'aether_skyforest';
            }
        }
    }
    
    // Lazy-spawn dimension workers on first entry. We can't rely on the
    // request functions to do it because the dispatch loop only calls them
    // when workerActive is true, which itself requires the worker to already
    // be spawned and ready.
    if (typeof currentDimension !== 'undefined') {
        if (currentDimension === 'nether') {
            if (!_netherWorker && !_netherWorkerInitInFlight) {
                spawnNetherWorker();
            }
        } else if (currentDimension === 'aether') {
            if (!_aetherWorker && !_aetherWorkerInitInFlight) {
                spawnAetherWorker();
            }
        }
    }
}
window.notifyDimensionChange = notifyDimensionChange;

// ==========================================
// MESH BUILDER WORKER (background mesh build)
// ==========================================
// Builds chunk meshes in a background thread. The worker maintains its own
// mirror of chunkStorageArr and biomeMap. Main thread sends each chunk to
// the worker once on first request, then re-sends only when modified.
// Worker returns Float32Array buffers via Transferable; main thread uses
// _assembleChunkMeshFromArrays to create THREE.BufferGeometry objects.

let _meshWorker = null;
let _meshWorkerReady = false;
const _pendingMeshRequests = new Set(); // "cx,cz" keys currently being built by worker
const _meshWorkerChunkVersions = new Map(); // "cx,cz" -> version number the worker has
const _mainThreadChunkVersions = new Map(); // "cx,cz" -> our current version
const _biomeStripsSent = new Set(); // "cx,cz" keys whose biome strip has been sent
let _meshWorkerCompletedThisFrame = 0;

// Bump the version of a chunk to mark it as needing re-sync to the worker.
// Called when a chunk is generated, modified, or has its lighting changed.
function bumpChunkVersion(cx, cz) {
    const key = cx + ',' + cz;
    _mainThreadChunkVersions.set(key, (_mainThreadChunkVersions.get(key) || 0) + 1);
}
window.bumpChunkVersion = bumpChunkVersion;

function spawnMeshWorker() {
    console.log('[mesh-worker] spawning...');
    if (_meshWorker) {
        try { _meshWorker.terminate(); } catch(e) {}
        _meshWorker = null;
    }
    _meshWorkerReady = false;
    _pendingMeshRequests.clear();
    _meshWorkerChunkVersions.clear();
    _mainThreadChunkVersions.clear();
    _biomeStripsSent.clear();
    
    if (typeof Worker === 'undefined') {
        console.warn('[mesh-worker] Web Workers not supported, falling back to inline mesh build');
        return;
    }
    
    try {
        _meshWorker = new Worker('js/workers/mesh-worker.js?v=' + (typeof ASSET_VERSION !== 'undefined' ? ASSET_VERSION : Date.now()));
    } catch (e) {
        console.warn('[mesh-worker] failed to spawn, falling back to inline mesh:', e);
        _meshWorker = null;
        return;
    }
    
    _meshWorker.onerror = function(ev) {
        console.error('[mesh-worker] error:', ev.message, ev.filename, ev.lineno);
        _meshWorkerReady = false;
    };
    
    _meshWorker.onmessage = function(ev) {
        const msg = ev.data;
        if (msg.type === 'initDone') {
            _meshWorkerReady = true;
            console.log('[mesh-worker] ready');
            return;
        }
        if (msg.type === 'error') {
            console.error('[mesh-worker] error:', msg.error);
            _meshWorkerReady = false;
            return;
        }
        if (msg.type === 'meshError') {
            const wcx = msg.wcx !== undefined ? msg.wcx : msg.cx;
            const wcz = msg.wcz !== undefined ? msg.wcz : msg.cz;
            console.error('[mesh-worker] mesh error for chunk', wcx, wcz, ':', msg.error);
            _pendingMeshRequests.delete(wcx + ',' + wcz);
            // Fall back to inline build
            try { buildChunkMesh(wcx, wcz); } catch (e) { console.error(e); }
            return;
        }
        if (msg.type === 'meshDone') {
            _onMeshWorkerDone(msg);
            return;
        }
    };
    
    // Send init message
    _meshWorker.postMessage({
        type: 'init',
        WORLD_WIDTH: WORLD_WIDTH,
        WORLD_DEPTH: WORLD_DEPTH,
        CHUNKS_X: CHUNKS_X,
        CHUNKS_Z: CHUNKS_Z,
        CHUNK_VOLUME: CHUNK_VOLUME,
        BLOCK_DATA: BLOCK_DATA,
        settings: {
            settingGraphicsFancy: typeof settingGraphicsFancy !== 'undefined' ? settingGraphicsFancy : true,
            settingSmoothLighting: typeof settingSmoothLighting !== 'undefined' ? settingSmoothLighting : true,
            settingGraphicsFabulous: typeof settingGraphicsFabulous !== 'undefined' ? settingGraphicsFabulous : false
        }
    });
}
